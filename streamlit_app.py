"""
Mini Zia — Automated Business Insight Generator (web demo).

A thin Streamlit UI over the existing rule-based insight engine. It runs the
full pipeline (anomaly detection -> period comparison -> root cause -> natural
language insights) on synthetic KPI data or an uploaded CSV, and shows the
results the way a business user would read them.

The insights are fully deterministic and explainable. An optional LLM
rephrasing layer exists in the codebase but is intentionally disabled in this
public demo (no API keys, no cost, nothing sent to a third party).
"""

from __future__ import annotations

import contextlib
import io

import pandas as pd
import streamlit as st

from data_generator import generate_business_data
from insight_engine import InsightEngine
from main import MiniZia

REQUIRED_COLUMNS = ["date", "region", "segment", "sales", "leads", "conversion_rate"]

PRIORITY_STYLE = {
    "critical": ("🔴", "#ef4444"),
    "high": ("🟠", "#f59e0b"),
    "medium": ("🟡", "#eab308"),
    "low": ("🟢", "#22c55e"),
}


st.set_page_config(page_title="Mini Zia — Business Insight Generator", page_icon="🤖", layout="wide")


@st.cache_data(show_spinner=False)
def load_sample_data(days: int, seed: int = 42) -> pd.DataFrame:
    """Generate reproducible synthetic business data."""
    return generate_business_data(days=days, seed=seed)


def validate_dataframe(df: pd.DataFrame) -> list[str]:
    """Return a list of human-readable validation errors (empty = valid)."""
    errors: list[str] = []
    missing = [c for c in REQUIRED_COLUMNS if c not in df.columns]
    if missing:
        errors.append(f"Missing required column(s): {', '.join(missing)}")
    if len(df) == 0:
        errors.append("The file has no rows.")
    if len(df) > 200_000:
        errors.append("Please keep the dataset under 200,000 rows for this demo.")
    return errors


def run_pipeline(df: pd.DataFrame, params: dict) -> tuple[dict, str]:
    """Run MiniZia.analyze while capturing its console output. Returns (results, log)."""
    buffer = io.StringIO()
    with contextlib.redirect_stdout(buffer):
        zia = MiniZia(
            anomaly_threshold_std=params["threshold_std"],
            anomaly_threshold_pct=params["threshold_pct"],
            significance_threshold=params["significance"],
            enable_llm=False,
        )
        results = zia.analyze(
            df,
            current_period_days=params["current_days"],
            previous_period_days=params["previous_days"],
            region_filter=params["region"],
            segment_filter=params["segment"],
        )
        results["_summary_metrics"] = zia.generate_summary_metrics(results)
        results["_report"] = InsightEngine().format_insight_report(results["insights"])
    return results, buffer.getvalue()


# ── Header ───────────────────────────────────────────────────────────────────

st.title("🤖 Mini Zia")
st.caption("Automated Business Insight Generator — turns raw KPI data into plain-English insights.")

st.info(
    "**Demo note:** insights are generated by a **deterministic, rule-based engine** — no black box, "
    "fully explainable. The data below is **synthetic** (or your uploaded CSV). An optional LLM "
    "rephrasing layer exists in the code but is **disabled here** (no API keys, nothing sent anywhere).",
    icon="ℹ️",
)

# ── Sidebar controls ─────────────────────────────────────────────────────────

with st.sidebar:
    st.header("Data")
    source = st.radio("Source", ["Sample data", "Upload CSV"], index=0)

    uploaded_df: pd.DataFrame | None = None
    if source == "Sample data":
        days = st.slider("Days of history to generate", 30, 120, 90, step=10)
    else:
        days = 90
        st.caption(f"CSV must have columns: {', '.join(REQUIRED_COLUMNS)}")
        st.download_button(
            "⬇ Download sample CSV template",
            data=load_sample_data(30).to_csv(index=False).encode("utf-8"),
            file_name="mini_zia_sample.csv",
            mime="text/csv",
            use_container_width=True,
        )
        upload = st.file_uploader("Upload your KPI CSV", type=["csv"])
        if upload is not None:
            try:
                uploaded_df = pd.read_csv(upload)
                uploaded_df["date"] = pd.to_datetime(uploaded_df["date"], errors="coerce")
            except Exception as exc:  # noqa: BLE001 - surface any parse error to the user
                st.error(f"Could not read CSV: {exc}")
                uploaded_df = None

    st.header("Comparison window")
    current_days = st.slider("Current period (days)", 1, 30, 7)
    previous_days = st.slider("Previous period (days)", 1, 30, 7)

    st.header("Filters")
    # Regions/segments are discovered from the data once it's loaded below.
    region_choice = st.session_state.get("_region_choice", "All")
    segment_choice = st.session_state.get("_segment_choice", "All")

    with st.expander("Advanced thresholds"):
        threshold_std = st.number_input("Anomaly threshold (std devs)", 0.5, 5.0, 2.0, 0.5)
        threshold_pct = st.number_input("Anomaly threshold (% change)", 5.0, 50.0, 15.0, 5.0)
        significance = st.number_input("Trend significance (%)", 5.0, 50.0, 10.0, 5.0)

# ── Resolve the working dataframe ────────────────────────────────────────────

if source == "Upload CSV":
    if uploaded_df is None:
        st.warning("Upload a CSV in the sidebar (or switch to **Sample data**) to run an analysis.")
        st.stop()
    errors = validate_dataframe(uploaded_df)
    if errors:
        for err in errors:
            st.error(err)
        st.stop()
    working_df = uploaded_df
else:
    working_df = load_sample_data(days)

# Region / segment filters now that we know the data
regions = ["All", *sorted(working_df["region"].dropna().unique().tolist())]
segments = ["All", *sorted(working_df["segment"].dropna().unique().tolist())]
with st.sidebar:
    region_choice = st.selectbox("Region", regions, index=0, key="_region_choice")
    segment_choice = st.selectbox("Segment", segments, index=0, key="_segment_choice")
    run = st.button("▶ Run analysis", type="primary", use_container_width=True)

# ── Run & render ─────────────────────────────────────────────────────────────

if not run:
    st.subheader("How to use this")
    st.markdown(
        "1. Pick **Sample data** (or upload your own KPI CSV).\n"
        "2. Choose the **comparison window** (e.g. this week vs last week).\n"
        "3. Optionally filter by **region** or **segment**.\n"
        "4. Click **Run analysis** — Mini Zia will flag anomalies, compare periods, "
        "find the likely root cause, and write an executive summary with recommendations."
    )
    st.dataframe(working_df.head(12), use_container_width=True)
    st.stop()

params = {
    "current_days": current_days,
    "previous_days": previous_days,
    "region": None if region_choice == "All" else region_choice,
    "segment": None if segment_choice == "All" else segment_choice,
    "threshold_std": threshold_std,
    "threshold_pct": threshold_pct,
    "significance": significance,
}

try:
    with st.spinner("Analysing…"):
        results, log = run_pipeline(working_df, params)
except Exception as exc:  # noqa: BLE001 - never crash the UI; show the error instead
    st.error(f"Analysis failed: {exc}")
    st.stop()

insights = results["insights"]
metrics = results["_summary_metrics"]
priority = insights.get("priority", "medium")
emoji, color = PRIORITY_STYLE.get(priority, ("🟡", "#eab308"))

# KPI tiles
c1, c2, c3, c4 = st.columns(4)
c1.metric("Records analysed", f"{len(working_df):,}")
c2.metric("Groups compared", metrics.get("regions_analyzed", "—"))
c3.metric("Anomalies detected", metrics.get("total_anomalies", 0))
c4.metric("Significant changes", metrics.get("significant_changes", 0))

# Headline
st.markdown(
    f"<div style='padding:14px 18px;border-radius:12px;border:1px solid {color}55;"
    f"background:{color}12;margin:8px 0 4px'>"
    f"<span style='font-weight:700'>{emoji} Priority: {priority.upper()}</span><br>"
    f"<span style='font-size:1.1rem'>{insights.get('summary', 'No significant changes detected')}</span></div>",
    unsafe_allow_html=True,
)

# Insights + recommendations
left, right = st.columns(2)
with left:
    st.subheader("Key insights")
    details = insights.get("details", [])
    if details:
        for d in details:
            st.markdown(f"- {d.strip().splitlines()[0]}")
            rest = d.strip().splitlines()[1:]
            if rest:
                st.caption("  \n".join(line.strip() for line in rest))
    else:
        st.caption("No notable details for this selection.")
with right:
    st.subheader("Recommendations")
    recs = insights.get("recommendations", [])
    if recs:
        for r in recs:
            st.markdown(f"- {r.replace('💡', '').strip()}")
    else:
        st.caption("No specific recommendations — metrics look stable.")

# Anomalies
anomalies = results.get("anomalies", [])
if anomalies:
    st.subheader("Anomalies")
    acols = st.columns(min(3, len(anomalies)))
    for i, a in enumerate(anomalies[:3]):
        with acols[i % len(acols)]:
            dev = float(a.get("deviation_pct", 0))
            arrow = "📉" if dev < 0 else "📈"
            st.metric(
                f"{arrow} {a.get('region', '—')} · {str(a.get('metric', '')).title()}",
                f"{dev:+.1f}%",
                help=f"{a.get('anomaly_type', '').replace('_', ' ')}",
            )

# Trend chart
st.subheader("Sales trend by region")
try:
    pivot = working_df.groupby(["date", "region"])["sales"].sum().unstack()
    st.line_chart(pivot, height=280)
except Exception:  # noqa: BLE001 - chart is best-effort
    st.caption("Trend chart unavailable for this dataset shape.")

# Period comparison table
comparison = results.get("comparisons")
if comparison is not None and len(comparison) > 0:
    with st.expander("Period-over-period comparison (table)"):
        show_cols = [
            c
            for c in [
                "region",
                "segment",
                "sales_change_pct",
                "leads_change_pct",
                "conversion_rate_change_pct",
                "sales_is_anomaly",
            ]
            if c in comparison.columns
        ]
        st.dataframe(comparison[show_cols].round(2), use_container_width=True)

# Full report + engine trace
with st.expander("Full report & engine trace"):
    st.text(results.get("_report", ""))
    if log.strip():
        st.caption("Pipeline log")
        st.code(log, language="text")

st.divider()
st.caption(
    "Mini Zia · rule-based (explainable) insight engine · synthetic demo data · "
    "optional LLM rephrasing disabled in this demo."
)
